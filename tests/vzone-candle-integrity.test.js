'use strict';
const assert=require('node:assert/strict');
const {validateCandle,filterValidBars}=require('../vzone-candle-integrity');
const now=Date.now();
const good={o:100,h:105,l:99,c:104,t:now-3600000};
assert.equal(validateCandle(good,now).valid,true);
assert.equal(validateCandle({o:100,h:99,l:98,c:98},now).valid,false,'high below open must be rejected');
assert.equal(validateCandle({o:100,h:105,l:106,c:104},now).valid,false,'low above high must be rejected');
assert.equal(validateCandle({o:100,h:105,l:99,c:104,t:now+3600000},now).valid,false,'future candle must be rejected');
assert.equal(validateCandle({o:100,h:105,l:99,c:104,t:now-1000},now,900000).valid,false,'active M15 candle must be rejected');
assert.equal(validateCandle({o:100,h:105,l:99,c:104,t:now-900000},now,900000).valid,true,'closed M15 candle is valid');
const out=filterValidBars([good,{o:100,h:99,l:98,c:98},{o:100,h:105,l:99,c:104,t:now+3600000}],now);
assert.equal(out.length,1,'only valid candles may enter signal engine');
console.log('V-Zone candle integrity tests: PASS');
